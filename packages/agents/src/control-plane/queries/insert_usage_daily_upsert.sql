INSERT INTO usage_daily (
  bucket,
  day,
  charged_agent_id,
  credential_id,
  credential_kind,
  provider,
  model,
  actor_kind,
  usage_state,
  attempts,
  failed,
  rate_limited,
  input,
  output,
  cache_read,
  cache_write,
  total_tokens,
  reasoning,
  cache_write_1h,
  reasoning_reported,
  cache_write_1h_reported,
  cost_usd
)
SELECT
  :bucket::text,
  :day::text,
  :chargedAgentId::text,
  :credentialId::nullable(text),
  :credentialKind::nullable(text),
  :provider::text,
  :model::text,
  :actorKind::text,
  :usageState::text,
  1,
  :failed::int,
  :rateLimited::int,
  :input::int,
  :output::int,
  :cacheRead::int,
  :cacheWrite::int,
  :totalTokens::int,
  :reasoning::int,
  :cacheWrite1h::int,
  :reasoningReported::int,
  :cacheWrite1hReported::int,
  :costUsd::real
FROM usage_ingestion
WHERE agent_id = :agentId
  AND last_seq = :after
ON CONFLICT (bucket) DO UPDATE SET
  attempts = usage_daily.attempts + excluded.attempts,
  failed = usage_daily.failed + excluded.failed,
  rate_limited = usage_daily.rate_limited + excluded.rate_limited,
  input = usage_daily.input + excluded.input,
  output = usage_daily.output + excluded.output,
  cache_read = usage_daily.cache_read + excluded.cache_read,
  cache_write = usage_daily.cache_write + excluded.cache_write,
  total_tokens = usage_daily.total_tokens + excluded.total_tokens,
  reasoning = usage_daily.reasoning + excluded.reasoning,
  cache_write_1h = usage_daily.cache_write_1h + excluded.cache_write_1h,
  reasoning_reported = usage_daily.reasoning_reported + excluded.reasoning_reported,
  cache_write_1h_reported = usage_daily.cache_write_1h_reported + excluded.cache_write_1h_reported,
  cost_usd = usage_daily.cost_usd + excluded.cost_usd;
